# Build PdfCraft for the browser, without the ArtCraft marks (patches/), into web/.
#
# PdfCraft has the embedding bridge this app uses since storytold/pdfcraft#842 (b34b326). The
# patch only adds the `unbranded` feature: a build we make is a modified version of PdfCraft,
# which must not carry the ArtCraft marks (docs/brand/LICENSE-brand.txt).
#
# Usage: scripts/build-pdfcraft-web.sh [PDFCRAFT_CHECKOUT]
#
#   PDFCRAFT_CHECKOUT  an existing clone of github.com/storytold/pdfcraft. Without it the
#                      script clones PDFCRAFT_REF into build/printcraft.
#
# Needs: Rust with the wasm32-unknown-unknown target (rustup target add wasm32-unknown-unknown)
# and wasm-bindgen-cli at the version in PdfCraft's Cargo.lock
# (cargo install wasm-bindgen-cli --version <x.y.z> --locked). wasm-opt (binaryen) is used
# when installed and shrinks the download by about a third.
#
# Environment:
#   PDFCRAFT_REF   commit or tag to clone (default: the commit the patch was made against)
#   BUILD_STD=1    build the standard library from source (when the wasm32 target can't be
#                  installed through rustup but rust-src is available)
#   FAST=1         skip LTO and use parallel codegen: quicker builds, bigger wasm
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PDFCRAFT_REF="${PDFCRAFT_REF:-924c4da4ac2879ac9107c6c82e20ac6be5570f0a}"
SRC="${1:-$APP_DIR/build/printcraft}"
PATCH="$APP_DIR/patches/pdfcraft-nextcloud.patch"
OUT="$APP_DIR/web"
TARGET_DIR="${CARGO_TARGET_DIR:-$SRC/target}"

if [ ! -e "$SRC/.git" ]; then
	git clone https://github.com/storytold/pdfcraft.git "$SRC"
	git -C "$SRC" checkout --quiet "$PDFCRAFT_REF"
fi

if ! grep -q 'host_save' "$SRC/crates/ui-egui/src/lib.rs"; then
	echo "error: this PdfCraft has no embedding bridge; use b34b326 (storytold/pdfcraft#842) or later" >&2
	exit 1
fi
if grep -q '^unbranded' "$SRC/crates/ui-egui/Cargo.toml"; then
	echo "unbranded patch already applied"
else
	git -C "$SRC" apply "$PATCH"
fi

# `unbranded`: a modified PdfCraft must not carry the ArtCraft marks (docs/brand/LICENSE-brand.txt).
cargo_args=(build --release -p pdfcraft-web --target wasm32-unknown-unknown --features unbranded)
if [ "${BUILD_STD:-0}" = "1" ]; then
	export RUSTC_BOOTSTRAP=1
	cargo_args+=(-Zbuild-std=std,panic_abort)
fi
if [ "${FAST:-0}" = "1" ]; then
	export CARGO_PROFILE_RELEASE_LTO=off CARGO_PROFILE_RELEASE_CODEGEN_UNITS=16
fi
(cd "$SRC" && CARGO_TARGET_DIR="$TARGET_DIR" cargo "${cargo_args[@]}")

WASM_IN="$TARGET_DIR/wasm32-unknown-unknown/release/pdfcraft-web.wasm"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
wasm-bindgen --target web --no-typescript --out-dir "$STAGE" --out-name pdfcraft-web "$WASM_IN"

if command -v wasm-opt >/dev/null; then
	wasm-opt -Oz --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext \
		--enable-mutable-globals --enable-reference-types --enable-multivalue \
		"$STAGE/pdfcraft-web_bg.wasm" -o "$STAGE/pdfcraft-web_bg.opt.wasm"
	mv "$STAGE/pdfcraft-web_bg.opt.wasm" "$STAGE/pdfcraft-web_bg.wasm"
else
	echo "note: wasm-opt not found; the wasm is not size-optimized"
fi

# Content-hashed names: Nextcloud lets browsers cache app assets for months.
hash() { sha256sum "$1" | cut -c1-16; }
JS_NAME="pdfcraft-web-$(hash "$STAGE/pdfcraft-web.js").js"
WASM_NAME="pdfcraft-web-$(hash "$STAGE/pdfcraft-web_bg.wasm").wasm"

mkdir -p "$OUT"
rm -f "$OUT"/pdfcraft-web-*.js "$OUT"/pdfcraft-web-*.wasm
cp "$STAGE/pdfcraft-web.js" "$OUT/$JS_NAME"
cp "$STAGE/pdfcraft-web_bg.wasm" "$OUT/$WASM_NAME"

# PdfCraft's licenses and the attributions for the fonts and icons compiled into it.
for f in LICENSE-MIT LICENSE-APACHE NOTICE ATTRIBUTION.md; do
	if [ -f "$SRC/$f" ]; then cp "$SRC/$f" "$OUT/PDFCRAFT-$f"; fi
done

cat > "$OUT/boot.js" <<EOF
/*
 * SPDX-FileCopyrightText: 2026 Britton Couchman <brittondcouchman@gmail.com>
 * SPDX-License-Identifier: AGPL-3.0-or-later
 *
 * Starts PdfCraft in the editor's iframe (templates/frame.php).
 * Generated by scripts/build-pdfcraft-web.sh from PdfCraft $(git -C "$SRC" rev-parse --short HEAD).
 */

function reportFailure(error) {
	console.error('PdfCraft could not start', error)
	if (window.parent !== window) {
		window.parent.postMessage({ type: 'pdfcraft:failed', error: String(error?.message ?? error) }, window.location.origin)
	}
}

try {
	const { default: init } = await import('./$JS_NAME')
	await init({ module_or_path: new URL('./$WASM_NAME', import.meta.url) })
} catch (error) {
	reportFailure(error)
}
EOF

echo "PdfCraft web build:"
ls -lh "$OUT"
